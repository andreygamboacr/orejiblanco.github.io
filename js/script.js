/* =========================================================
   ACTUALIZAR METADATOS SEO
   ========================================================= */

function updateSEO(language) {

    const t = translations[language];

    document.title = t.title;


    const description = document.querySelector(
        'meta[name="description"]'
    );

    if (description) {
        description.setAttribute(
            "content",
            t.description
        );
    }


    const ogTitle = document.querySelector(
        'meta[property="og:title"]'
    );

    if (ogTitle) {
        ogTitle.setAttribute(
            "content",
            t.ogTitle
        );
    }


    const ogDescription = document.querySelector(
        'meta[property="og:description"]'
    );

    if (ogDescription) {
        ogDescription.setAttribute(
            "content",
            t.ogDescription
        );
    }


    const ogLocale = document.querySelector(
        'meta[property="og:locale"]'
    );

    if (ogLocale) {

        ogLocale.setAttribute(
            "content",
            language === "en"
                ? "en_US"
                : "es_CR"
        );

    }

}


/* =========================================================
   CAMBIO DE IDIOMA
   ========================================================= */

function setLanguage(
    language,
    savePreference = false
) {


    /* Idioma válido */

    if (!translations[language]) {
        language = "es";
    }


    const t = translations[language];


    /* Idioma del documento */

    document.documentElement.lang = language;


    /* SEO */

    updateSEO(language);


    /* =====================================================
       TEXTOS
    ===================================================== */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.getAttribute("data-i18n");


            if (t[key] !== undefined) {

                element.innerHTML =
                    t[key];

            }

        });


    /* =====================================================
       ALT DE IMÁGENES
    ===================================================== */

    document
        .querySelectorAll("[data-i18n-alt]")
        .forEach(element => {

            const key =
                element.getAttribute("data-i18n-alt");


            if (t[key] !== undefined) {

                element.setAttribute(
                    "alt",
                    t[key]
                );

            }

        });


    /* =====================================================
       GUARDAR PREFERENCIA MANUAL
    ===================================================== */

    if (savePreference) {

        localStorage.setItem(
            "orejiblanco-language",
            language
        );

    }


    /* =====================================================
       BOTONES ES / EN
    ===================================================== */

    document
        .querySelectorAll("[data-language]")
        .forEach(button => {

            button.classList.toggle(
                "active",
                button.getAttribute(
                    "data-language"
                ) === language
            );

        });

}


/* =========================================================
   DETECTAR IDIOMA DEL NAVEGADOR
   ========================================================= */

function detectLanguage() {


    /* =====================================================
       Preferencia guardada
    ===================================================== */

    const savedLanguage =
        localStorage.getItem(
            "orejiblanco-language"
        );


    if (
        savedLanguage &&
        translations[savedLanguage]
    ) {

        return savedLanguage;

    }


    /* =====================================================
       Idiomas del navegador
    ===================================================== */

    const browserLanguages =
        navigator.languages ||
        [navigator.language] ||
        ["es"];


    const hasEnglish =
        browserLanguages.some(
            language =>
                language
                    .toLowerCase()
                    .startsWith("en")
        );


    if (hasEnglish) {
        return "en";
    }


    return "es";

}


/* =========================================================
   INICIAR SITIO
   ========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    () => {


        /* Idioma inicial */

        const detectedLanguage =
            detectLanguage();


        setLanguage(
            detectedLanguage,
            false
        );


        /* =================================================
           BOTONES ES / EN
        ================================================== */

        document
            .querySelectorAll("[data-language]")
            .forEach(button => {


                button.addEventListener(
                    "click",
                    () => {


                        const language =
                            button.getAttribute(
                                "data-language"
                            );


                        setLanguage(
                            language,
                            true
                        );


                    }
                );


            });


    }
);